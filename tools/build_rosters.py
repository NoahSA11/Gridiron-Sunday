#!/usr/bin/env python3
"""Build compact roster files for Gridiron Sunday from the nflverse roster feed.

Source: https://github.com/nflverse/nflverse-data/releases/download/rosters/roster_<season>.csv
(open data, updated daily by the nflverse project).

Usage:
  python3 -I build_rosters.py <roster.csv> <out_dir> [--snapshot]

Writes <out_dir>/rosters.json (the live feed the game polls) and, with
--snapshot, also <out_dir>/js/rosters-snapshot.js (the offline fallback bundled
into the page).

Compact player row: [name, pos, depthPos, jersey, age, heightIn, weightLb, yearsExp, draftPick]
draftPick 0 = undrafted.
"""
import csv, json, sys, os, datetime

def age_on(birth, today):
    try:
        y, m, d = map(int, birth.split('-'))
        return today.year - y - ((today.month, today.day) < (m, d))
    except Exception:
        return 26

def main():
    src, out = sys.argv[1], sys.argv[2]
    snapshot = '--snapshot' in sys.argv
    today = datetime.date.today()
    rows = list(csv.DictReader(open(src, newline='', encoding='utf-8')))
    teams, season, week = {}, None, 0
    for r in rows:
        if r.get('status') != 'ACT':
            continue
        season = r.get('season') or season
        try: week = max(week, int(r.get('week') or 0))
        except ValueError: pass
        def num(k, dflt=0):
            try: return int(float(r.get(k) or dflt))
            except ValueError: return dflt
        teams.setdefault(r['team'], []).append([
            r['full_name'], r['position'], r['depth_chart_position'] or r['position'],
            num('jersey_number'), age_on(r.get('birth_date', ''), today),
            num('height', 73), num('weight', 230), num('years_exp'), num('draft_number')])
    if len(teams) < 32:
        sys.exit('feed looks incomplete: %d teams' % len(teams))
    data = {
        'source': 'nflverse roster feed (github.com/nflverse/nflverse-data)',
        'season': int(season), 'week': week,
        'updated': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'teams': teams,
    }
    blob = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
    open(os.path.join(out, 'rosters.json'), 'w', encoding='utf-8').write(blob)
    if snapshot:
        open(os.path.join(out, 'js', 'rosters-snapshot.js'), 'w', encoding='utf-8').write(
            '/* Bundled fallback roster snapshot. Generated by tools/build_rosters.py */\n'
            'window.ROSTER_SNAPSHOT=' + blob + ';\n')
    print('teams', len(teams), 'players', sum(len(v) for v in teams.values()), 'bytes', len(blob))

if __name__ == '__main__':
    main()
